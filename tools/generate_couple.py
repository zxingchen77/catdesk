def validate_drawing(drawing):
    rows = drawing.split()
    assert len(rows) == 24
    assert all(len(row) == 16 and set(row) <= set("0123456789") for row in rows)
    assert set("".join(rows)) == set("0123456789")
    for y, row in enumerate(rows):
        for x, pixel in enumerate(row):
            if pixel in "01":
                continue
            for nx, ny in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)):
                assert 0 <= nx < 16 and 0 <= ny < 24 and rows[ny][nx] != "0", \
                    f"Missing outline at ({x}, {y})"
    return rows


def main():
    drawings = ((BOY_FRONT, BOY_SIDE, BOY_SIT, BOY_WALK_A, BOY_WALK_B),
                (GIRL_FRONT, GIRL_SIDE, GIRL_SIT, GIRL_WALK_A, GIRL_WALK_B))
    lines = ["/* Generated by tools/generate_couple.py. Original art; 1,920 bytes. */",
             "static const uint8_t people[2][5][24][8] = {"]
    for person in range(2):
        lines.append("    {")
        for pose in range(5):
            rows = validate_drawing(drawings[person][pose])
            lines.append("        {")
            for row in rows:
                packed = [int(row[x]) * 16 + int(row[x + 1]) for x in range(0, 16, 2)]
                lines.append("            {" + ",".join(f"0x{value:02x}" for value in packed) + "},")
            lines.append("        },")
        lines.append("    },")
    lines.append("};")
    target = Path(__file__).resolve().parents[1] / "firmware/components/catdesk_ui/catdesk_people.inc"
    target.write_text("\n".join(lines) + "\n")
    print("Packed ten original 16x24 poses; nine colors/person; 1,920 sprite bytes.")


if __name__ == "__main__":
    main()
